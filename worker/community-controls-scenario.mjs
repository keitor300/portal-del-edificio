import assert from 'node:assert/strict';
import { expect } from '@playwright/test';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

export async function runCommunityControls({ admin, owner, neighbor, base, pdf }) {
  assert.equal(new URL(base).hostname, '127.0.0.1');
  const state = async () => (await (await owner.request.get(`${base}/api/state`)).json()).data;
  const future = new Date(Date.now() + 8 * 86400000).toISOString().slice(0, 10);
  const yesterday = new Date(Date.now() - 3 * 86400000).toISOString().slice(0, 10);
  const failOnce = async (page, url) => page.route(url, route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'SIMULACRO: servicio temporalmente no disponible' }) }), { times: 1 });
  const meetingTitle = 'SIMULACRO - Reunion y acta completas';
  await admin.goto(`${base}/admin/comunidad?tab=reuniones&new=1`);
  let form = admin.getByRole('dialog');
  await form.getByLabel('Título', { exact: true }).fill(meetingTitle);
  await form.getByLabel('Fecha', { exact: true }).fill(future);
  await form.getByLabel('Lugar', { exact: true }).fill('SUM');
  await form.getByLabel('Orden del día').fill('Revisar luminarias\nEvaluar propuestas');
  await form.getByLabel('Hora de inicio', { exact: true }).fill('19:00');
  await form.getByLabel('Hora de finalización (opcional)').fill('18:00');
  await form.getByRole('button', { name: 'Guardar reunión', exact: true }).click();
  await expect(form.getByRole('alert')).toContainText('posterior al de inicio');
  await form.getByLabel('Hora de finalización (opcional)').fill('20:00');
  await failOnce(admin, '**/api/entities/meetings');
  await form.getByRole('button', { name: 'Guardar reunión', exact: true }).click();
  await expect(form.getByRole('alert')).toContainText('servicio temporalmente no disponible');
  await expect(form.getByLabel('Título', { exact: true })).toHaveValue(meetingTitle);
  await form.getByRole('alert').scrollIntoViewIfNeeded();
  await admin.screenshot({ path: join(tmpdir(), 'portal-community-retry.png') });
  await form.getByRole('button', { name: 'Guardar reunión', exact: true }).click();
  await expect(form).toHaveCount(0);
  await owner.goto(`${base}/demo/propietario/edificio/reuniones`);
  await expect(owner.locator('.community-meeting').filter({ hasText: meetingTitle })).toContainText('Revisar luminarias');
  for (const status of ['Cancelada', 'Realizada']) {
    await admin.getByRole('button', { name: `Editar ${meetingTitle}`, exact: true }).click();
    form = admin.getByRole('dialog');
    await form.getByLabel('Estado', { exact: true }).selectOption(status);
    if (status === 'Realizada') {
      await form.getByLabel('Resumen del acta (opcional)').fill('Resumen ficticio de la reunion.');
      await form.getByLabel('Decisiones acordadas (opcional)').fill('Solicitar presupuesto\nPublicar el avance');
      await form.getByLabel(/^Documentación o acta/).setInputFiles({ name: 'acta-simulacro.pdf', mimeType: 'application/pdf', buffer: pdf });
      await expect(form.getByText('acta-simulacro.pdf', { exact: true })).toBeVisible();
    }
    await form.getByRole('button', { name: 'Guardar reunión', exact: true }).click();
    await expect(form).toHaveCount(0);
    await owner.reload();
    await expect(owner.locator('.community-meeting').filter({ hasText: meetingTitle })).toHaveCount(0);
    await owner.getByRole('button', { name: `Ver detalle de ${meetingTitle}`, exact: true }).click();
    const detail = owner.getByRole('dialog', { name: meetingTitle, exact: true });
    await expect(detail).toContainText(status);
    if (status === 'Realizada') {
      await expect(detail).toContainText('Solicitar presupuesto');
      await expect(detail).toContainText('Publicar el avance');
      await detail.getByRole('button', { name: 'Ver acta o documento', exact: true }).click();
      await expect(owner.getByRole('dialog', { name: 'acta-simulacro.pdf', exact: true })).toBeVisible();
      await owner.keyboard.press('Escape');
      await expect(owner.getByRole('dialog', { name: 'acta-simulacro.pdf', exact: true })).toHaveCount(0);
      await expect(detail).toBeVisible();
      await expect(detail.getByRole('button', { name: 'Ver acta o documento', exact: true })).toBeFocused();
    }
    await detail.getByRole('button', { name: 'Cerrar', exact: true }).click();
  }

  const pollTitle = 'SIMULACRO - Votacion con vencimiento';
  await admin.goto(`${base}/admin/comunidad?tab=votaciones&new=1`);
  form = admin.getByRole('dialog');
  await form.getByLabel('Título', { exact: true }).fill(pollTitle);
  await form.getByLabel(/^Opciones/).fill('A favor\na favor');
  await form.getByRole('button', { name: 'Guardar votación', exact: true }).click();
  await expect(form.getByRole('alert')).toContainText('diferentes entre sí');
  await form.getByLabel(/^Opciones/).fill('A favor\nEn contra\nAbstención');
  await failOnce(admin, '**/api/entities/polls');
  await form.getByRole('button', { name: 'Guardar votación', exact: true }).click();
  await expect(form.getByRole('alert')).toContainText('servicio temporalmente no disponible');
  await form.getByLabel('Fecha de cierre (opcional)').fill(yesterday);
  await form.getByRole('button', { name: 'Guardar votación', exact: true }).click();
  await expect(form.getByRole('alert')).toContainText('elegí una fecha de cierre desde hoy');
  await form.getByLabel('Estado', { exact: true }).selectOption('cerrada');
  await form.getByRole('button', { name: 'Guardar votación', exact: true }).click();
  await expect(form).toHaveCount(0);
  await owner.goto(`${base}/demo/propietario/edificio/encuestas`);
  const poll = owner.getByRole('article', { name: pollTitle, exact: true });
  await expect(poll).toHaveCount(0);
  await owner.getByRole('button', { name: 'Cerradas', exact: true }).click();
  await expect(poll).toContainText('Todavía no se registraron votos.');
  await expect(poll.getByRole('radio')).toHaveCount(0);
  await admin.getByRole('button', { name: `Reabrir ${pollTitle}`, exact: true }).click();
  await expect(admin.getByRole('dialog')).toBeVisible();
  await admin.getByRole('dialog').getByLabel('Fecha de cierre (opcional)').fill(future);
  await admin.getByRole('button', { name: 'Guardar votación', exact: true }).click();
  await expect(admin.getByRole('dialog')).toHaveCount(0);
  await owner.reload();
  await owner.getByRole('button', { name: 'Abiertas', exact: true }).click();
  await expect(poll.getByRole('button', { name: 'Registrar voto', exact: true })).toBeDisabled();
  await poll.getByRole('radio', { name: 'A favor', exact: true }).check();
  await poll.getByRole('button', { name: 'Registrar voto', exact: true }).click();
  await expect(poll.getByRole('status')).toContainText('Tu voto: A favor');
  await admin.getByRole('button', { name: `Cerrar ${pollTitle}`, exact: true }).click();
  await expect(admin.getByRole('button', { name: `Reabrir ${pollTitle}`, exact: true })).toBeVisible();
  await neighbor.goto(`${base}/demo/propietario/edificio/encuestas`);
  await neighbor.getByRole('button', { name: 'Todas', exact: true }).click();
  const neighborPoll = neighbor.getByRole('article', { name: pollTitle, exact: true });
  await expect(neighborPoll).toContainText('1 de 52 unidades');
  await expect(neighborPoll.getByRole('radio')).toHaveCount(0);
  await admin.getByRole('button', { name: `Reabrir ${pollTitle}`, exact: true }).click();
  await expect(admin.getByRole('button', { name: `Cerrar ${pollTitle}`, exact: true })).toBeVisible();
  await neighbor.reload();
  await neighborPoll.getByRole('radio', { name: 'En contra', exact: true }).check();
  await neighborPoll.getByRole('button', { name: 'Registrar voto', exact: true }).click();
  await expect(neighborPoll).toContainText('2 de 52 unidades');
  await admin.getByRole('button', { name: `Resultados de ${pollTitle}`, exact: true }).click();
  await expect(admin.getByRole('dialog')).toContainText('2 de 52 unidades', { timeout: 20000 });
  await expect(admin.getByRole('dialog').getByRole('meter', { name: 'A favor: 1 votos, 50 %', exact: true })).toHaveAttribute('value', '1');
  await admin.getByRole('dialog').getByRole('button', { name: 'Cerrar', exact: true }).click();
  assert.deepEqual((await state()).polls.find(row => row.title === pollTitle).votes, [1, 1, 0]);

  await owner.goto(`${base}/demo/propietario/edificio/reuniones?tab=temas`);
  await owner.getByRole('button', { name: 'Proponer tema', exact: true }).click();
  form = owner.getByRole('dialog');
  await form.getByLabel('Título del tema').fill('   ');
  await form.getByLabel('Contanos tu propuesta').fill('Propuesta ficticia para el simulacro.');
  await form.getByRole('button', { name: 'Enviar tema', exact: true }).click();
  await expect(form.getByRole('alert')).toContainText('Completá el título');
  const topicTitle = 'SIMULACRO - Tema con reintento';
  await form.getByLabel('Título del tema').fill(topicTitle);
  await failOnce(owner, '**/api/entities/topics');
  await form.getByRole('button', { name: 'Enviar tema', exact: true }).click();
  await expect(form.getByRole('alert')).toContainText('servicio temporalmente no disponible');
  await form.getByRole('button', { name: 'Enviar tema', exact: true }).click();
  await expect(form).toHaveCount(0);
  await owner.getByRole('button', { name: `Comentarios de ${topicTitle}`, exact: true }).click();
  form = owner.getByRole('dialog');
  await form.getByLabel('Agregar un comentario').fill('   ');
  await form.getByRole('button', { name: 'Publicar comentario', exact: true }).click();
  await expect(form.getByRole('alert')).toContainText('Escribí un comentario');
  await form.getByLabel('Agregar un comentario').fill('Comentario ficticio con reintento.');
  await failOnce(owner, '**/api/topics/*/comments');
  await form.getByRole('button', { name: 'Publicar comentario', exact: true }).click();
  await expect(form.getByRole('alert')).toContainText('servicio temporalmente no disponible');
  await form.getByRole('button', { name: 'Publicar comentario', exact: true }).click();
  await expect(form.getByText('Comentario ficticio con reintento.', { exact: true })).toBeVisible();
  await expect(form.getByRole('alert')).toHaveCount(0);
  await form.getByRole('button', { name: 'Cerrar', exact: true }).click();
  const topics = (await state()).topics;
  assert.equal(topics.find(row => row.title === topicTitle).messages.length, 1);
  await admin.goto(`${base}/admin/comunidad?tab=temas`);
  for (const status of ['Pendiente', 'En agenda', 'Resuelto', 'No incluido', 'Todos']) {
    await admin.getByLabel('Filtrar por estado').selectOption(status);
    await expect(admin.locator('li.list-row')).toHaveCount(topics.filter(row => status === 'Todos' || row.status === status).length);
  }
  console.log('Simulation verified: meeting records, expired formal polls, owner filters and corrected-validation retries');
}
