import assert from 'node:assert/strict';
import { expect } from '@playwright/test';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

export async function runSumControls({ owner, admin, neighbor, base }) {
  assert.equal(new URL(base).hostname, '127.0.0.1');
  const dateAt = offset => new Date(Date.now() + offset * 86400000).toISOString().slice(0, 10);
  let offset = 65;
  while (new Date(`${dateAt(offset)}T12:00:00Z`).getUTCDay() !== 5) offset++;
  const friday = dateAt(offset), monday = dateAt(offset + 3);
  const reservations = async () => (await (await owner.request.get(`${base}/api/state`)).json()).data.reservations;
  const start = page => page.getByLabel('Hora de inicio', { exact: true });
  const end = page => page.getByLabel('Hora de finalización', { exact: true });
  await owner.goto(`${base}/demo/propietario/servicios/sum`);
  await expect(owner.getByLabel('Unidad que reserva')).toBeDisabled();
  await expect(owner.getByLabel('Unidad que reserva')).toHaveValue('7B');
  await expect(end(owner)).toBeDisabled();
  await owner.getByRole('button', { name: 'Foto completa', exact: true }).click();
  const photo = owner.getByRole('dialog').getByRole('img', { name: 'Fotografía completa del salón de usos múltiples del edificio', exact: true });
  await expect(photo).toBeVisible();
  assert.ok(await photo.evaluate(image => image.complete && image.naturalWidth > 0));
  await owner.keyboard.press('Escape');
  await expect(owner.getByRole('dialog')).toHaveCount(0);
  await expect(owner.getByRole('button', { name: 'Foto completa', exact: true })).toBeFocused();

  await owner.getByLabel('Fecha de reserva').fill(friday);
  const values = await start(owner).locator('option').evaluateAll(options => options.map(option => option.value).filter(Boolean));
  assert.equal(values[0], '08:30');
  assert.ok(values.every(value => /^\d{2}:(00|30)$/.test(value)));
  await start(owner).selectOption('22:00');
  await end(owner).selectOption('03:00');
  await owner.getByLabel('Fecha de reserva').fill(monday);
  await expect(start(owner)).toHaveValue('');
  await expect(end(owner)).toBeDisabled();
  await start(owner).selectOption('22:00');
  await expect(end(owner).locator('option[value="03:00"]')).toHaveCount(0);
  await end(owner).selectOption('01:00');
  await start(owner).selectOption('23:00');
  await expect(end(owner)).toHaveValue('');
  await end(owner).selectOption('01:00');
  await owner.getByRole('button', { name: 'Continuar con la reserva', exact: true }).click();
  await expect(owner.getByRole('alert')).toContainText(/reglamento/i);
  await expect(owner.getByRole('dialog')).toHaveCount(0);
  await owner.getByRole('checkbox').check();
  await owner.getByRole('button', { name: 'Continuar con la reserva', exact: true }).click();
  await expect(owner.getByRole('dialog')).toContainText('continúa el');
  await owner.getByRole('dialog').getByRole('button', { name: 'Volver', exact: true }).click();
  assert.equal((await reservations()).filter(row => row.date === monday).length, 0);
  await expect(start(owner)).toHaveValue('23:00');
  await owner.getByRole('button', { name: 'Continuar con la reserva', exact: true }).click();
  await owner.getByRole('button', { name: 'Confirmar reserva', exact: true }).click();
  await expect(owner.getByRole('dialog')).toHaveCount(0);
  const created = (await reservations()).find(row => row.date === monday);
  assert.equal(created.unit, '7B');
  assert.equal(created.endDate, dateAt(offset + 4));

  await neighbor.goto(`${base}/demo/propietario/servicios/sum`);
  const otherRow = neighbor.locator('.reservation-row').filter({ hasText: '23:00 a 01:00' });
  await expect(otherRow).toContainText('Unidad 7B');
  await expect(otherRow.getByRole('button')).toHaveCount(0);
  await admin.goto(`${base}/admin/servicios?tab=sum`);
  await admin.getByLabel('Filtrar por unidad').fill('NO-EXISTE');
  await expect(admin.getByText('No hay reservas para este filtro.', { exact: true })).toBeVisible();
  await admin.getByLabel('Filtrar por unidad').fill('7b');
  await expect(admin.locator('.reservation-row').filter({ hasText: '23:00 a 01:00' })).toBeVisible();

  await owner.goto(`${base}/demo/propietario/mas/calendario`);
  const currentMonth = await owner.getByLabel('Mes', { exact: true }).inputValue();
  await owner.getByRole('button', { name: 'Mes siguiente', exact: true }).click();
  assert.notEqual(await owner.getByLabel('Mes', { exact: true }).inputValue(), currentMonth);
  await owner.getByRole('button', { name: 'Mes anterior', exact: true }).click();
  await expect(owner.getByLabel('Mes', { exact: true })).toHaveValue(currentMonth);
  await owner.getByLabel('Mes', { exact: true }).fill(monday.slice(0, 7));
  await owner.getByLabel('Tipo de evento').selectOption('reservations');
  await owner.getByRole('button', { name: 'Ver Reserva del SUM', exact: true }).click();
  await expect(owner.getByRole('dialog')).toContainText('23:00 a 01:00');
  await owner.getByRole('dialog').getByRole('button', { name: 'Cerrar', exact: true }).click();
  await owner.getByLabel('Tipo de evento').selectOption('works');
  await expect(owner.getByText('No hay eventos de este tipo en el mes seleccionado.', { exact: true })).toBeVisible();
  await owner.getByRole('button', { name: 'Mes actual', exact: true }).click();
  await expect(owner.getByLabel('Mes', { exact: true })).toHaveValue(currentMonth);

  await owner.goto(`${base}/demo/propietario/servicios/sum`);
  const ownRow = owner.locator('.reservation-row').filter({ hasText: '23:00 a 01:00' });
  await ownRow.getByRole('button').click();
  await owner.getByRole('dialog').getByRole('button', { name: 'Volver', exact: true }).click();
  assert.equal((await reservations()).find(row => row.id === created.id).status, 'Confirmada');
  await ownRow.getByRole('button').click();
  await owner.getByRole('dialog').getByRole('button', { name: 'Confirmar', exact: true }).click();
  await expect(ownRow).toHaveCount(0);
  for (const filter of ['Canceladas', 'Todas']) {
    await owner.getByLabel('Mostrar reservas').selectOption(filter);
    await expect(ownRow).toContainText('Cancelada');
    await expect(ownRow.getByRole('button')).toHaveCount(0);
  }
  await owner.goto(`${base}/demo/propietario/mas/calendario`);
  await owner.getByLabel('Mes', { exact: true }).fill(monday.slice(0, 7));
  await owner.getByLabel('Tipo de evento').selectOption('reservations');
  await expect(owner.getByText('No hay eventos de este tipo en el mes seleccionado.', { exact: true })).toBeVisible();

  await admin.getByLabel('Fecha a bloquear').fill(friday);
  await admin.getByRole('button', { name: 'Bloquear día', exact: true }).click();
  const unblock = admin.getByRole('button', { name: /^Desbloquear / });
  await expect(unblock).toHaveCount(1);
  await admin.getByRole('button', { name: 'Bloquear día', exact: true }).click();
  await expect(admin.getByRole('alert')).toContainText('ya está bloqueada');
  await owner.goto(`${base}/demo/propietario/servicios/sum`);
  await owner.getByLabel('Fecha de reserva').fill(friday);
  await start(owner).selectOption('08:30');
  await end(owner).selectOption('10:00');
  await owner.getByRole('checkbox').check();
  await owner.getByRole('button', { name: 'Continuar con la reserva', exact: true }).click();
  await expect(owner.getByRole('alert')).toContainText(/bloquead/i);
  await expect(owner.getByRole('dialog')).toHaveCount(0);
  await unblock.click();
  await expect(unblock).toHaveCount(0);
  await owner.reload();
  await owner.getByLabel('Fecha de reserva').fill(friday);
  await start(owner).selectOption('08:30');
  await end(owner).selectOption('10:00');
  await owner.getByRole('checkbox').check();
  await owner.getByRole('button', { name: 'Continuar con la reserva', exact: true }).click();
  await expect(owner.getByRole('dialog', { name: 'Confirmar reserva del SUM' })).toBeVisible();
  await owner.getByRole('dialog').getByRole('button', { name: 'Volver', exact: true }).click();
  assert.equal((await reservations()).filter(row => row.date === friday).length, 0);
  await owner.screenshot({ path: join(tmpdir(), 'portal-simulacro-sum-controls.png'), fullPage: true });
  console.log('Simulation verified: SUM time controls, photo, filters, cancellation, calendar and blocked dates');
}
